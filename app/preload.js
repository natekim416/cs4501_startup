// The only bridge between the UI and the backend. The UI cannot touch files directly.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  init: () => ipcRenderer.invoke('init'),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  scan: (folder) => ipcRenderer.invoke('scan', folder),
  prepareTour: () => ipcRenderer.invoke('prepare-tour'),
  plan: (request) => ipcRenderer.invoke('plan', request),
  answer: (question, choice) => ipcRenderer.invoke('answer', question, choice),
  execute: (planId, ids, opts) => ipcRenderer.invoke('execute', planId, ids, opts),
  undo: () => ipcRenderer.invoke('undo'),
  setZone: (zonePath, zone) => ipcRenderer.invoke('set-zone', zonePath, zone),
  changeZone: (zonePath, zone) => ipcRenderer.invoke('change-zone', zonePath, zone),
  setTarget: (destRoot) => ipcRenderer.invoke('set-target', destRoot),
  forget: (pref) => ipcRenderer.invoke('forget', pref),
  protect: (names) => ipcRenderer.invoke('protect', names),
  unprotect: (name) => ipcRenderer.invoke('unprotect', name),
  setUsage: (on) => ipcRenderer.invoke('set-usage', on),
  goPro: () => ipcRenderer.invoke('go-pro'),
  setSemesterEnd: (date) => ipcRenderer.invoke('set-semester-end', date),
  setStorageWatch: (on) => ipcRenderer.invoke('set-storage-watch', on),
  dismissStorageWatch: () => ipcRenderer.invoke('dismiss-storage-watch'),
  rebuild: (recipe) => ipcRenderer.invoke('rebuild', recipe),
  undoOne: (batchId, actionId) => ipcRenderer.invoke('undo-one', batchId, actionId),
  exportUsage: () => ipcRenderer.invoke('export-usage'),
  capture: () => ipcRenderer.invoke('capture'),
  onAttempt: (fn) => ipcRenderer.on('attempt', (_e, attempt) => fn(attempt)),
  onUsage: (fn) => ipcRenderer.on('usage', (_e, status) => fn(status)),
  onStorageAlert: (fn) => ipcRenderer.on('storage-alert', (_e, notice) => fn(notice)),
  onStoragePreview: (fn) => ipcRenderer.on('storage-preview', () => fn()),
  onBreakdownProgress: (fn) => ipcRenderer.on('breakdown-progress', (_e, progress) => fn(progress)),
});
